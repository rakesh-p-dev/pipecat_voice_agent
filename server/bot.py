SONIOX_STT_URLS = {
    "us": "wss://stt-rt.soniox.com/transcribe-websocket",
    "jp": "wss://stt-rt.soniox.com/transcribe-websocket",
    "in": os.getenv("SONIOX_STT_URL_IN", "wss://stt-rt.soniox.com/transcribe-websocket"),
}


def get_soniox_endpoint():
    """Resolve (region, api_key, url) based on SONIOX_STT_REGION."""
    region = (os.getenv("SONIOX_STT_REGION") or "in").strip().lower()
    if region not in SONIOX_STT_URLS:
        logger.warning(f"Soniox: unknown region {region!r}, using default")
        region = "in"

    api_key = os.getenv("SONIOX_API_KEY_IN") if region == "in" else os.getenv("SONIOX_API_KEY")
    if not api_key:
        api_key = os.getenv("SONIOX_API_KEY") or os.getenv("SONIOX_API_KEY_IN")

    url = os.getenv("SONIOX_STT_URL", SONIOX_STT_URLS.get(region, "wss://stt-rt.soniox.com/transcribe-websocket"))
    return region, api_key, url


def get_language_hints() -> list[Language]:
    """Default language hints: Tamil + English for natural code-switching."""
    raw_lang = os.getenv("STT_LANGUAGE", "ta")
    hints = []
    for code in [raw_lang, "en"]:
        try:
            lang = Language(code)
            if lang not in hints:
                hints.append(lang)
        except ValueError:
            continue
    if Language.TA not in hints:
        hints.insert(0, Language.TA)
    if Language.EN not in hints:
        hints.append(Language.EN)
    return hints


async def run_bot(transport: BaseTransport, runner_args: RunnerArguments) -> None:
    """Run the voice bot for this session."""
    logger.info("Starting bot")

    # Soniox endpoint & credentials resolution
    region, soniox_api_key, soniox_url = get_soniox_endpoint()
    logger.info(f"Soniox region: {region} ({soniox_url})")

    max_delay = int(os.getenv("SONIOX_MAX_ENDPOINT_DELAY_MS", "500"))
    latency_level = int(os.getenv("SONIOX_ENDPOINT_LATENCY_LEVEL", "3"))
    sensitivity = float(os.getenv("SONIOX_ENDPOINT_SENSITIVITY", "0.3"))
    vad_force = os.getenv("SONIOX_VAD_FORCE_ENDPOINT", "0") in ("1", "true", "True")

    # Speech-to-Text service (Soniox)
    stt = SonioxSTTService(
        api_key=soniox_api_key,
        url=soniox_url,
        settings=SonioxSTTService.Settings(
            model=os.getenv("SONIOX_STT_MODEL", "stt-rt-v5"),
            language_hints=get_language_hints(),
            language_hints_strict=False,
            max_endpoint_delay_ms=max_delay,
            endpoint_latency_adjustment_level=latency_level,
            endpoint_sensitivity=sensitivity,
        ),
        vad_force_turn_endpoint=vad_force,
    )

    # Text-to-Speech service (ElevenLabs Dialogue - v3/v4 models)
    # stability: 0.0 to 1.0 (lower values like 0.3-0.4 increase expressiveness and emotion)
    tts = ElevenLabsDialogueTTSService(
        api_key=os.getenv("ELEVENLABS_API_KEY"),
        settings=ElevenLabsDialogueTTSService.Settings(
            voice=os.getenv("ELEVENLABS_VOICE_ID", "pTX8uGyVgHCWLj6IkcbC"),
            model=os.getenv("ELEVENLABS_MODEL", "eleven_v4_turbo"),
            stability=float(os.getenv("ELEVENLABS_STABILITY", "0.35")),
        ),
    )
    system_prompt="""
You are Priya, a friendly and helpful customer support agent at SmartPhone Hub, T. Nagar, Chennai. You speak in a mix of Tamil and English (Tanglish) and are always"""

    async def end_call(params: FunctionCallParams):
        """End the call once the user has said goodbye or the conversation is finished."""
        await params.result_callback({"success": True})
        await params.llm.push_frame(EndWorkerFrame())

    # LLM service (Google Gemini)
    llm = GoogleLLMService(
        api_key=os.getenv("GEMINI_API_KEY"),
        settings=GoogleLLMService.Settings(
            model=os.getenv("GEMINI_MODEL", os.getenv("VERTEX_LLM_MODEL", "gemini-2.5-flash")),
            system_instruction=SYSTEM_PROMPT,
        ),
    )

    context = LLMContext(tools=[end_call])
    user_aggregator, assistant_aggregator = LLMContextAggregatorPair(
        context,
        user_params=LLMUserAggregatorParams(vad_analyzer=SileroVADAnalyzer()),
    )

    # Pipeline - assembled from reusable components
    pipeline = Pipeline(
        [
            transport.input(),
            stt,
            user_aggregator,
            llm,
            tts,
            transport.output(),
            assistant_aggregator,
        ]
    )

    worker = PipelineWorker(
        pipeline,
        params=PipelineParams(
            enable_metrics=True,
            enable_usage_metrics=True,
        ),
        observers=[],
    )

    runner = WorkerRunner(handle_sigint=runner_args.handle_sigint)

    await runner.add_workers(worker)

    @worker.rtvi.event_handler("on_client_ready")
    async def on_client_ready(rtvi):
        # Kick off the conversation in natural Tanglish
        context.add_message(
            {
                "role": "developer",
                "content": "Greet the customer warmly in Chennai Tanglish as Priya from SmartPhone Hub, T. Nagar and ask how you can help them today.",
            }
        )
        await worker.queue_frames([LLMRunFrame()])

    @transport.event_handler("on_client_connected")
    async def on_client_connected(transport, client):
        logger.info("Client connected")

    @transport.event_handler("on_client_disconnected")
    async def on_client_disconnected(transport, client):
        logger.info("Client disconnected")
        await runner.cancel()

    await runner.run()


async def bot(runner_args: RunnerArguments):
    """Main bot entry point."""

    transport_params = {
        "daily": lambda: DailyParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
        "webrtc": lambda: TransportParams(
            audio_in_enabled=True,
            audio_out_enabled=True,
        ),
    }

    transport = await create_transport(runner_args, transport_params)

    await run_bot(transport, runner_args)


if __name__ == "__main__":
    from pipecat.runner.run import main

    main()
